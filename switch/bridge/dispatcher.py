from __future__ import annotations
"""Command and message dispatcher for Switch events."""

import logging
import re
from typing import Any, Callable, Coroutine, Dict, List, Optional

from switch.bridge.schemas import CommandPayload, OutboundMessage, SwitchEvent, SwitchMessage

logger = logging.getLogger("vayu.switch.dispatcher")

VAYU_AGENT_IDS = {"vayu-analyst", "vayu-remediator", "vayu-gatekeeper", "vayu"}


class MessageDispatcher:
    """Dispatches incoming Switch room events to targeted agent handlers."""

    def __init__(self) -> None:
        self._command_handlers: Dict[str, Callable[[CommandPayload], Coroutine[Any, Any, Optional[OutboundMessage]]]] = {}
        self._agent_handlers: Dict[str, Callable[[SwitchMessage], Coroutine[Any, Any, Optional[OutboundMessage]]]] = {}

    def register_command(
        self,
        command: str,
        handler: Callable[[CommandPayload], Coroutine[Any, Any, Optional[OutboundMessage]]],
    ) -> None:
        """Register a handler for a slash command (e.g., '/vayu scan', '/approve')."""
        self._command_handlers[command.lower()] = handler

    def register_agent(
        self,
        agent_id: str,
        handler: Callable[[SwitchMessage], Coroutine[Any, Any, Optional[OutboundMessage]]],
    ) -> None:
        """Register a handler for direct mentions to a named agent."""
        self._agent_handlers[agent_id.lower()] = handler

    async def handle_event(self, event: SwitchEvent) -> Optional[OutboundMessage]:
        """Process an inbound Switch event and execute the corresponding agent handler."""
        if event.event_type != "message.created":
            logger.debug(f"Ignoring non-message event: {event.event_type}")
            return None

        try:
            msg = SwitchMessage(**event.data)
        except Exception as exc:
            logger.error(f"Malformed SwitchMessage payload: {exc}")
            return None

        # Guard: Ignore messages generated by our own agents to prevent feedback loops
        if msg.sender.type == "agent" and msg.sender.id.lower() in VAYU_AGENT_IDS:
            return None

        content = msg.content.strip()

        # 1. Check for slash commands: e.g. "/vayu scan ...", "/approve ...", "/reject ..."
        if content.startswith("/"):
            parts = content.split()
            cmd_root = parts[0].lower()
            
            # Check for two-part commands like "/vayu scan" or "/vayu investigate"
            if cmd_root == "/vayu" and len(parts) > 1:
                cmd_key = f"/vayu {parts[1].lower()}"
                cmd_args = parts[2:]
            else:
                cmd_key = cmd_root
                cmd_args = parts[1:]

            if cmd_key in self._command_handlers:
                payload = CommandPayload(
                    command=cmd_key,
                    args=cmd_args,
                    raw_content=content,
                    room_id=msg.room_id,
                    sender=msg.sender,
                )
                return await self._command_handlers[cmd_key](payload)

        # 2. Check for @mentions
        for mention in msg.mentions:
            clean_mention = mention.lower().lstrip("@")
            if clean_mention in self._agent_handlers:
                return await self._agent_handlers[clean_mention](msg)

        # 3. Check for implicit mentions in text (e.g. "@vayu-analyst investigate ...")
        for agent_id, handler in self._agent_handlers.items():
            pattern = rf"@?{re.escape(agent_id)}\b"
            if re.search(pattern, content, re.IGNORECASE):
                return await handler(msg)

        # 4. Fallback: if message mentions "@vayu" generically, default to vayu-analyst triage
        if re.search(r"@?vayu\b", content, re.IGNORECASE) and "vayu-analyst" in self._agent_handlers:
            return await self._agent_handlers["vayu-analyst"](msg)

        return None

